const {test}=require('node:test'),assert=require('node:assert/strict'),{readFileSync}=require('node:fs')
const api=import('data:text/javascript;base64,'+Buffer.from(readFileSync(`${__dirname}/projectIdleCycle.js`,'utf8')).toString('base64'))
test('idle cycles loop projects without needing a scroll API and input smoothly restores the native selection',async()=>{
  const cycle=(await api).createProjectIdleCycle(3)
  cycle.sample(0,0,true,0)
  assert.equal(cycle.sample(1999,0,true,0).automatic,false)
  let frame=cycle.sample(2000,0,true,0);assert.equal(frame.to,1);assert.equal(frame.mix,0)
  frame=cycle.sample(2850,0,true,0);assert.equal(frame.index,1)
  cycle.sample(4850,0,true,0);assert.equal(cycle.sample(5700,0,true,0).index,2)
  cycle.sample(7700,0,true,0);assert.equal(cycle.sample(8550,0,true,0).index,0)
  cycle.sample(10550,0,true,0);cycle.sample(11400,0,true,0)
  frame=cycle.sample(11410,0,false,11410);assert.equal(frame.returning,true);assert.equal(frame.from,1)
  frame=cycle.sample(11710,0,false,11410);assert.equal(frame.index,0)
  assert.equal(cycle.sample(11800,0,false,11410).automatic,false)
})
test('hover/focus freezes the displayed project and remaining dwell; offscreen and single-project scenes stay safe',async()=>{
  const cycle=(await api).createProjectIdleCycle(3)
  cycle.sample(0,0,true,0);cycle.sample(2000,0,true,0);cycle.sample(2850,0,true,0)
  assert.equal(cycle.sample(3000,0,false,0).index,1)
  assert.equal(cycle.sample(30000,0,false,0).index,1)
  cycle.sample(31000,0,true,0)
  assert.equal(cycle.sample(32000,0,true,0).index,1)
  assert.equal(cycle.sample(32000,0,false,0,false),null)
  const single=(await api).createProjectIdleCycle(1);single.sample(0,0,true,0)
  assert.equal(single.sample(90000,0,true,0).automatic,false)
})
