const assert = require('node:assert/strict')
const { test } = require('node:test')
const { readFileSync } = require('node:fs')
const apiPromise = import(`data:text/javascript;base64,${Buffer.from(readFileSync(`${__dirname}/journeyCarouselMotion.js`, 'utf8')).toString('base64')}`)
function charge(api, state) {
  const start=state.nowMs
  while (state.phase==='ready' && state.nowMs-start<6000) api.inputJourneyCarousel(state,20,state.nowMs+20)
  assert.equal(state.phase,'absorbing')
}
function start(api, lengths, headings) {
  const state=api.createJourneyCarousel(lengths,headings)
  for(let now=20;state.phase==='gate' && now<=6000;now+=20) api.inputJourneyCarousel(state,20,now)
  assert.equal(state.phase,'charging')
  api.advanceJourneyCarousel(state,state.phaseStarted+api.JOURNEY_CHARGE_MS+api.JOURNEY_FORM_MS)
  assert.equal(state.phase,'reading')
  state.nowMs=0
  state.phaseStarted=0
  return state
}
test('first memory stays hidden until an initial charge completes',async()=>{
  const api=await apiPromise,state=api.createJourneyCarousel([130],[40])
  const sample=api.sampleJourneyCarousel(state,10000)
  assert.equal(sample.phase,'gate')
  assert.equal(sample.carouselOpacity,0)
  assert.equal(sample.headingCharacters,0)
  assert.equal(sample.coreOpacity,1)
  for(let i=0;i<5;i++) api.inputJourneyCarousel(state,120,state.nowMs+100)
  assert.equal(state.phase,'gate')
  const startTime=state.nowMs
  while(state.phase==='gate' && state.nowMs-startTime<6000) api.inputJourneyCarousel(state,20,state.nowMs+20)
  assert.equal(state.phase,'charging')
  const formed=api.sampleJourneyCarousel(state,state.phaseStarted+api.JOURNEY_CHARGE_MS+api.JOURNEY_FORM_MS)
  assert.equal(formed.phase,'reading')
})
test('after charging, title then body type without scroll',async()=>{
  const api=await apiPromise, state=start(api,[130],[40])
  assert.equal(state.phase,'reading')
  api.advanceJourneyCarousel(state,state.nowMs+500)
  assert.ok(Math.abs(state.headingCharacters-20)<.01)
  assert.equal(state.textCharacters,0)
  assert.equal(api.sampleJourneyCarousel(state,state.nowMs).coreOpacity,1)
  api.advanceJourneyCarousel(state,state.nowMs+1000)
  assert.equal(state.headingCharacters,40)
  assert.ok(Math.abs(state.textCharacters-32.5)<.01)
  api.advanceJourneyCarousel(state,state.nowMs+1500)
  assert.equal(state.phase,'ready')
  assert.equal(state.textCharacters,130)
  assert.equal(api.sampleJourneyCarousel(state,state.nowMs).coreOpacity,1)
})
test('scroll while typing cannot accelerate text or queue charge',async()=>{
  const api=await apiPromise,a=start(api,[650],[40]),b=start(api,[650],[40])
  for(let now=20;now<=6000;now+=20) api.inputJourneyCarousel(a,100000,now)
  api.advanceJourneyCarousel(b,6000)
  assert.ok(Math.abs(a.textCharacters-b.textCharacters)<.01)
  assert.equal(a.charge,0)
  assert.equal(a.scrollVelocity,0)
  api.advanceJourneyCarousel(a,18000)
  assert.equal(a.phase,'ready')
  assert.equal(a.charge,0)
})
test('clockwise idle rotation pauses during drag and resumes after a gentle release',async()=>{
  const api=await apiPromise,state=start(api,[650],[40])
  api.advanceJourneyCarousel(state,4000)
  const angle=state.rotation
  api.advanceJourneyCarousel(state,5000)
  assert.ok(state.rotation>angle)
  assert.equal(api.dragJourneyCarousel(state,0,true),true)
  api.dragJourneyCarousel(state,100,true,5020)
  const target=state.rotationTarget
  api.advanceJourneyCarousel(state,7000)
  assert.equal(state.rotationTarget,target)
  assert.ok(state.rotation<angle)
  api.dragJourneyCarousel(state,0,false)
  assert.equal(state.rotationVelocity,api.JOURNEY_IDLE_ROTATION)
  api.advanceJourneyCarousel(state,8000)
  assert.ok(state.rotationTarget>target)
})
test('only a strong fresh counterclockwise release coasts backward before returning clockwise',async()=>{
  const api=await apiPromise,state=start(api,[650],[40])
  api.advanceJourneyCarousel(state,4000)
  api.dragJourneyCarousel(state,0,true,4000)
  api.dragJourneyCarousel(state,80,true,4020)
  api.dragJourneyCarousel(state,80,true,4040)
  api.dragJourneyCarousel(state,0,false,4050)
  assert.ok(state.rotationVelocity<-.65)
  const releasedAngle=state.rotation
  api.advanceJourneyCarousel(state,4300)
  assert.ok(state.rotation<releasedAngle)
  api.advanceJourneyCarousel(state,8050)
  assert.ok(state.rotationVelocity>0)
  const returnedAngle=state.rotation
  api.advanceJourneyCarousel(state,10050)
  assert.ok(state.rotation>returnedAngle)
  // A tiny reverse adjustment has no counterclockwise release momentum.
  api.dragJourneyCarousel(state,0,true,10050)
  api.dragJourneyCarousel(state,1,true,10070)
  api.dragJourneyCarousel(state,0,false,10090)
  assert.equal(state.rotationVelocity,api.JOURNEY_IDLE_ROTATION)
})
