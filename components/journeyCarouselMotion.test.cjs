test('each memory needs fresh charge; centering finishes before scroll alone drives reversible ascent',async()=>{
  const api=await apiPromise,state=start(api,[30,40,50],[10,10,10])
  for(let index=0;index<3;index++){
    api.advanceJourneyCarousel(state,state.nowMs+5000)
    assert.equal(state.memoryIndex,index)
    assert.equal(state.phase,'ready')
    assert.equal(state.charge,0)
    charge(api,state)
    api.advanceJourneyCarousel(state,state.phaseStarted+api.JOURNEY_ABSORB_MS)
  }
  assert.equal(state.phase,'centering')
  const waiting=api.sampleJourneyCarousel(state,state.nowMs+api.JOURNEY_CENTER_MS+api.JOURNEY_CENTER_SETTLE_MS+60000)
  assert.equal(waiting.phase,'ascending')
  assert.equal(waiting.complete,false)
  assert.equal(waiting.ascend,0)
  assert.equal(waiting.coreX,.5)
  assert.equal(waiting.coreY,.5)
  api.inputJourneyCarouselAscent(state,.5,state.nowMs)
  const halfway=api.sampleJourneyCarousel(state,state.nowMs+10000)
  assert.equal(halfway.ascend,.5)
  assert.equal(halfway.coreY,0)
  assert.equal(halfway.complete,false)
  api.inputJourneyCarouselAscent(state,.5,state.nowMs)
  const end=api.sampleJourneyCarousel(state,state.nowMs)
  assert.equal(end.complete,true)
  assert.equal(end.coreOpacity,0)
  assert.equal(end.progress,1)
  api.inputJourneyCarouselAscent(state,-.25,state.nowMs)
  const reversed=api.sampleJourneyCarousel(state,state.nowMs+10000)
  assert.equal(reversed.phase,'ascending')
  assert.equal(reversed.complete,false)
  assert.equal(state.ascentProgress,.75)
  api.inputJourneyCarouselAscent(state,-10,state.nowMs)
  assert.equal(state.ascentProgress,0)
  assert.equal(api.sampleJourneyCarousel(state,state.nowMs).coreY,.5)
})
test('pinpoint shortcuts form the selected memory and reveal its text before enabling charge',async()=>{
  const api=await apiPromise,state=start(api,[65,130,195,260,325],[10,20,30,40,50])
  api.advanceJourneyCarousel(state,5000)
  api.seekJourneyCarousel(state,4,state.nowMs)
  assert.equal(state.memoryIndex,4)
  assert.equal(state.phase,'forming')
  assert.equal(state.headingCharacters,0)
  assert.equal(state.textCharacters,0)
  assert.equal(state.charge,0)
  api.advanceJourneyCarousel(state,state.nowMs+api.JOURNEY_FORM_MS)
  assert.equal(state.phase,'reading')
  api.inputJourneyCarousel(state,10000,state.nowMs+500)
  assert.equal(state.charge,0)
  assert.ok(state.headingCharacters>0 && state.headingCharacters<50)
  api.advanceJourneyCarousel(state,state.nowMs+10000)
  assert.equal(state.phase,'ready')
  assert.equal(state.textCharacters,325)
  assert.equal(state.charge,0)
})
test('upward gestures reconstruct each preceding memory instead of exiting to the introduction',async()=>{
  const api=await apiPromise,state=start(api,[65,130,195,260,325],[10,20,30,40,50])
  api.seekJourneyCarousel(state,4,state.nowMs)
  api.advanceJourneyCarousel(state,state.nowMs+10000)
  for(let index=4;index>0;index--){
    api.inputJourneyCarousel(state,-80,state.nowMs+500)
    assert.equal(state.phase,'ready')
    assert.equal(state.exitRequested,false)
    api.inputJourneyCarousel(state,-80,state.nowMs+20)
    assert.equal(state.phase,'erasing')
    assert.equal(state.phaseDirection,-1)
    api.advanceJourneyCarousel(state,state.nowMs+4000+api.JOURNEY_FORM_MS+api.JOURNEY_ABSORB_MS)
    assert.equal(state.phase,'ready')
    assert.equal(state.memoryIndex,index-1)
    assert.equal(state.headingCharacters,[10,20,30,40,50][index-1])
    assert.equal(state.textCharacters,[65,130,195,260,325][index-1])
    assert.equal(state.exitRequested,false)
    assert.equal(state.charge,0)
  }
  api.inputJourneyCarousel(state,-80,state.nowMs+500)
  api.inputJourneyCarousel(state,-80,state.nowMs+20)
  api.advanceJourneyCarousel(state,state.nowMs+4000+api.JOURNEY_FORM_MS+api.JOURNEY_CHARGE_MS)
  assert.equal(state.phase,'gate')
  assert.equal(state.exitRequested,false)
  api.inputJourneyCarousel(state,-80,state.nowMs+500)
  assert.equal(state.exitRequested,true)
})
test('a continuing upward momentum gesture cannot skip through several reconstructed memories',async()=>{
  const api=await apiPromise,state=start(api,[65,130,195],[10,20,30])
  api.seekJourneyCarousel(state,2,state.nowMs)
  api.advanceJourneyCarousel(state,state.nowMs+10000)
  api.inputJourneyCarousel(state,-100000,state.nowMs+20)
  assert.equal(state.phase,'ready')
  api.inputJourneyCarousel(state,-100000,state.nowMs+20)
  assert.equal(state.phase,'erasing')
  for(let elapsed=0;elapsed<8000;elapsed+=20) api.inputJourneyCarousel(state,-80,state.nowMs+20)
  assert.equal(state.phase,'ready')
  assert.equal(state.memoryIndex,1)
  assert.equal(state.exitRequested,false)
  api.inputJourneyCarousel(state,-80,state.nowMs+500)
  api.inputJourneyCarousel(state,-80,state.nowMs+20)
  assert.equal(state.phase,'erasing')
  api.advanceJourneyCarousel(state,state.nowMs+4000+api.JOURNEY_FORM_MS+api.JOURNEY_ABSORB_MS)
  assert.equal(state.memoryIndex,0)
  assert.equal(state.phase,'ready')
})
test('reverse final handoff replays centering and reconstructs the last historical photograph angle',async()=>{
  const api=await apiPromise,state=start(api,[65,130],[10,20])
  for(let index=0;index<2;index++){
    api.advanceJourneyCarousel(state,state.nowMs+5000)
    charge(api,state)
    api.advanceJourneyCarousel(state,state.nowMs+api.JOURNEY_ABSORB_MS)
  }
  const historicalAngle=state.memories[1].rotation
  api.advanceJourneyCarousel(state,state.nowMs+api.JOURNEY_CENTER_MS+api.JOURNEY_CENTER_SETTLE_MS)
  api.inputJourneyCarouselAscent(state,1,state.nowMs)
  assert.equal(api.rewindJourneyCarouselEnding(state,state.nowMs),false)
  api.inputJourneyCarouselAscent(state,-1,state.nowMs)
  assert.equal(api.rewindJourneyCarouselEnding(state,state.nowMs),true)
  assert.equal(state.phase,'centerSettle')
  assert.equal(state.phaseDirection,-1)
  api.advanceJourneyCarousel(state,state.nowMs+api.JOURNEY_CENTER_SETTLE_MS+api.JOURNEY_CENTER_MS+api.JOURNEY_ABSORB_MS)
  assert.equal(state.phase,'ready')
  assert.equal(state.memoryIndex,1)
  assert.equal(state.textCharacters,130)
  assert.equal(state.headingCharacters,20)
  assert.ok(Math.abs(state.rotation-historicalAngle)<1e-8)
  assert.equal(state.exitRequested,false)
})
test('clearing charge preserves ready memory and pinpoint selection resets pending reverse input',async()=>{
  const api=await apiPromise,state=start(api,[65,130],[10,20])
  api.advanceJourneyCarousel(state,5000)
  api.inputJourneyCarousel(state,80,state.nowMs+20)
  api.clearJourneyCarouselCharge(state,state.nowMs)
  assert.equal(state.phase,'ready')
  assert.equal(state.charge,0)
  assert.equal(state.textCharacters,65)
  api.inputJourneyCarousel(state,-80,state.nowMs+500)
  api.seekJourneyCarousel(state,1,state.nowMs)
  api.advanceJourneyCarousel(state,state.nowMs+10000)
  api.inputJourneyCarousel(state,-80,state.nowMs+20)
  assert.equal(state.phase,'ready')
  assert.equal(state.memoryIndex,1)
})
test('drag cannot disturb absorption; malformed input stays finite',async()=>{
  const api=await apiPromise,state=start(api,[65],[10])
  api.advanceJourneyCarousel(state,5000)
  api.dragJourneyCarousel(state,NaN,false)
  assert.ok(Number.isFinite(state.rotationTarget))
  charge(api,state)
  const rotation=state.rotationTarget
  assert.equal(api.dragJourneyCarousel(state,100,true),false)
  assert.equal(state.rotationTarget,rotation)
  api.inputJourneyCarousel(state,Infinity,state.nowMs)
  assert.ok(Number.isFinite(api.sampleJourneyCarousel(state,state.nowMs).rotation))
})
